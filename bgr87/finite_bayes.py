"""Finite-world Bayesian experiment planning with *persistent* action laws.

Exact for the DECLARED uniform prior over a finite catalogue of deterministic
2-bit, 2-action worlds; not Bayes optimal for arbitrary causal environments.
The hidden true world is never passed to the agent. The catalog is a
supplied prior, not learned operator invention. Neither hypothetical paths nor
posterior means count as certifications.
"""
from __future__ import annotations
from collections import defaultdict
from dataclasses import dataclass
from fractions import Fraction
from functools import lru_cache
from typing import Callable

STATES=((0,0),(0,1),(1,0),(1,1))
ACTIONS=('operation_0','operation_1')
GAMMA=Fraction(9,10)


def grammar_catalogue():
    """Distinct deterministic single-target logical effects on two binary fields."""
    rules=[]
    for target in (0,1):
        for label in ('set0','set1','flip','copy','not_other','xor','and','or'):
            outputs=[]
            for before in STATES:
                x,y=before[target],before[1-target]
                if label=='set0':v=0
                elif label=='set1':v=1
                elif label=='flip':v=1-x
                elif label=='copy':v=y
                elif label=='not_other':v=1-y
                elif label=='xor':v=x^y
                elif label=='and':v=x&y
                elif label=='or':v=x|y
                nxt=list(before);nxt[target]=v
                outputs.append(STATES.index(tuple(nxt)))
            rules.append({'name':f't{target}:{label}','target':target,'outcomes':tuple(outputs)})
    keys=[rule['outcomes'] for rule in rules]
    assert len(keys)==len(set(keys))==16, 'catalogue must represent a uniform prior over distinct functions'
    return tuple(rules)


CATALOGUE=grammar_catalogue()
RULE_COUNT=len(CATALOGUE)
MODEL_COUNT=RULE_COUNT**2


def true_transition(model_id:int,action:int,state_idx:int)->int:
    """Reference truth function, only environment uses a hidden model_id."""
    if not 0<=model_id<MODEL_COUNT:raise ValueError('unknown model id')
    if action not in (0,1):raise ValueError('action')
    if state_idx not in range(4):raise ValueError('state')
    rule=(model_id//RULE_COUNT) if action==0 else (model_id%RULE_COUNT)
    return CATALOGUE[rule]['outcomes'][state_idx]


# Each model is a fully specified, persistent pair of action laws.
TRANSITIONS=tuple(tuple(tuple(true_transition(m,a,s) for s in range(4)) for a in range(2)) for m in range(MODEL_COUNT))

class ModelViolation(Exception):
    """Observed effect cannot be generated by any surviving complete model."""

class ComputeBudgetExceeded(Exception):
    """Planner would exceed the announced deterministic node-expansion budget."""


def condition(ids:tuple[int,...],state:int,action:int,observed:int)->tuple[int,...]:
    """Bayes update for a uniform prior over surviving complete worlds."""
    posterior=tuple(m for m in ids if TRANSITIONS[m][action][state]==observed)
    if not posterior:raise ModelViolation('observed transition outside finite prior support')
    return posterior


def partition(ids:tuple[int,...],state:int,action:int)->dict[int,tuple[int,...]]:
    groups=defaultdict(list)
    for model in ids:groups[TRANSITIONS[model][action][state]].append(model)
    return dict(sorted((k,tuple(v)) for k,v in groups.items()))


@dataclass
class PlannerStats:
    calls:int=0
    exact_decisions:int=0
    fallback_decisions:int=0
    budget_exceeded:int=0
    posterior_updates:int=0
    nodes_expanded:int=0
    model_transition_checks:int=0
    last_decision:str=''
    last_value:str=''
    proven_symmetry_decisions:int=0
    proven_direct_goal_decisions:int=0
    cache_hits:int=0


class FiniteBelief:
    """Learning state: exact set of complete worlds consistent with history."""
    def __init__(self):
        self.ids=tuple(range(MODEL_COUNT));self.observations=[]
    def observe(self,old:int,action:int,new:int):
        before=self.ids
        fresh=condition(before,old,action,new)
        self.ids=fresh
        self.observations.append((old,action,new,len(fresh)))
    def certified(self,old:int,action:int):
        outs=partition(self.ids,old,action)
        return next(iter(outs)) if len(outs)==1 else None
    def possibilities(self,old:int,action:int):return tuple(partition(self.ids,old,action))


class ExactPlanner:
    """Exact finite-horizon Bayes-adaptive controller under known prior.

    Bellman value uses Fraction arithmetic: V=1 at goal, zero at horizon 0,
    and V=gamma * max_a sum_{outcomes} |B_out|/|B| V(next, B_out, h-1).

    This is a discounted success objective, not the probability of success
    alone. The prior assigns equal mass to the 256 complete-world models.
    A trusted `allowed` predicate can forbid any action with a possible
    successor outside scope. The planner never changes that predicate.
    """
    def __init__(self,goal:int,*,gamma=GAMMA,allowed:Callable[[int],bool]|None=None,
                 expansion_budget:int=1800):
        if goal not in range(4):raise ValueError('goal')
        if not 0<gamma<=1:raise ValueError('discount')
        if expansion_budget<1:raise ValueError('expansion_budget')
        self.goal=goal;self.gamma=Fraction(gamma);self.allowed=allowed
        self.expansion_budget=expansion_budget
        self.stats=PlannerStats()
        self._transpositions={}  # exact values reusable across real observations

    def exact_action(self,state:int,ids:tuple[int,...],steps_left:int):
        if state==self.goal:return None,Fraction(1)
        if steps_left<1:return None,Fraction(0)
        if self.allowed and not self.allowed(state):return None,Fraction(0)
        node_budget=self.expansion_budget
        costs={'nodes':0,'model_checks':0}
        def recurse(s,belief,h):
            if s==self.goal:return Fraction(1)
            if h<=0:return Fraction(0)
            key=(s,belief,h)
            if key in self._transpositions:
                self.stats.cache_hits+=1
                return self._transpositions[key]
            costs['nodes']+=1
            if costs['nodes']>node_budget:raise ComputeBudgetExceeded()
            best=Fraction(0)
            for a in (0,1):
                groups=partition(belief,s,a)
                costs['model_checks']+=len(belief)
                if self.allowed and any(not self.allowed(out) for out in groups):continue
                value=sum(Fraction(len(sub),len(belief))*recurse(out,sub,h-1) for out,sub in groups.items())
                best=max(best,self.gamma*value)
            if len(self._transpositions)<12000:
                self._transpositions[key]=best
            return best
        best=Fraction(-1);winning=None
        try:
            for a in (0,1):
                groups=partition(ids,state,a)
                costs['model_checks']+=len(ids)
                if self.allowed and any(not self.allowed(out) for out in groups):continue
                value=self.gamma*sum(Fraction(len(sub),len(ids))*recurse(out,sub,steps_left-1) for out,sub in groups.items())
                if value>best:
                    winning=a;best=value
        finally:
            self.stats.nodes_expanded+=costs['nodes'];self.stats.model_transition_checks+=costs['model_checks']
        if winning is None:return None,Fraction(0)
        return winning,best

    def myopic_action(self,state,ids,visits=None):
        if state==self.goal:return None
        best=None
        for a in (0,1):
            groups=partition(ids,state,a)
            self.stats.model_transition_checks+=len(ids)
            if self.allowed and any(not self.allowed(out) for out in groups):continue
            # Same prior as exact planner. Never treat model uniformity as
            # independently random transitions across successive actions.
            immediate=Fraction(len(groups.get(self.goal,())),len(ids))
            proximity=sum(Fraction(len(sub),len(ids))*Fraction(1,1+sum(x!=y for x,y in zip(STATES[out],STATES[self.goal]))) for out,sub in groups.items())
            novelty=-(visits.get((state,a),0) if visits else 0)
            score=(immediate,proximity,novelty,-a)
            if best is None or score>best[0]:best=(score,a)
        return best[1] if best else None

    def choose(self,state,belief:FiniteBelief,remaining:int,visits=None,mode='adaptive'):
        self.stats.calls+=1
        if self.allowed and (not self.allowed(state) or not self.allowed(self.goal)):
            self.stats.last_decision='scope_refusal';return None
        if state==self.goal:
            self.stats.last_decision='goal_reached';return None
        if mode not in ('adaptive','exact','myopic'):raise ValueError('mode')
        if mode=='myopic':
            self.stats.fallback_decisions+=1;self.stats.last_decision='myopic';return self.myopic_action(state,belief.ids,visits)
        if mode=='adaptive':
            # A unanimously correct one-step goal transition achieves maximum
            # possible discounted reward gamma; no other action can exceed it.
            for a in (0,1):
                unique=belief.certified(state,a)
                self.stats.model_transition_checks+=len(belief.ids)
                if unique==self.goal and (self.allowed is None or self.allowed(unique)):
                    self.stats.proven_direct_goal_decisions+=1
                    self.stats.last_decision='proven_direct_goal'
                    return a
            # Two action laws are exchangeable under the product uniform prior
            # iff their surviving rule sets are identical. Swapping labels is
            # a bijection between surviving complete worlds, hence Q0=Q1.
            left={m//RULE_COUNT for m in belief.ids}
            right={m%RULE_COUNT for m in belief.ids}
            if left==right and len(belief.ids)==len(left)*len(right):
                possible=partition(belief.ids,state,0)
                self.stats.model_transition_checks+=len(belief.ids)
                if self.allowed is None or all(self.allowed(s) for s in possible):
                    self.stats.proven_symmetry_decisions+=1
                    self.stats.last_decision='proven_action_symmetry'
                    return 0
        # Early attempts at exact planning can use a large state-space budget.
        # Deterministic computational control: if exact search cannot finish
        # before the node limit, fall back to a safe feasible myopic choice.
        try:
            a,v=self.exact_action(state,belief.ids,remaining)
            if a is not None:
                self.stats.exact_decisions+=1;self.stats.last_decision='exact';self.stats.last_value=str(v)
                return a
            self.stats.last_decision='no_permitted_action';return None
        except ComputeBudgetExceeded:
            self.stats.budget_exceeded+=1
            if mode=='exact':
                self.stats.last_decision='abstain_budget';return None
            self.stats.fallback_decisions+=1;self.stats.last_decision='fallback_budget'
            return self.myopic_action(state,belief.ids,visits)
