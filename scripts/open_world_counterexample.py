"""Constructive limitation of universal finite-trace certification.

For ANY finite action/partial-observation history, two unrestricted larger
finite Moore machines can agree on the history and disagree on the next full
observation, with at most length(history)+1 states. This is a standard
identifiability/no-free-lunch obstruction, not a new general-intelligence
mathematical theorem. It is separate from the preregistered bgr90 study.
"""
from dataclasses import dataclass
from random import Random
from bgr89.latent import code_to_bits

@dataclass(frozen=True)
class WitnessMachine:
    transitions:tuple[tuple[int,int],...]
    emissions:tuple[int,...]
    start:int=0


def compatible(code,obs):
    if len(obs)!=2:raise ValueError('observation should have two bits')
    return all(v is None or b==v for b,v in zip(code_to_bits(code),obs))


def completion_pair(evidence, next_action):
    """Evidence = [(None,initial_obs),(a1,obs1),...,(ak,obsk)].

    The prefix may be generated by ANY machine; the witness machines are
    NOT constrained by a fixed state-count bound. The last state's requested
    action has not been executed in this new path representation.
    """
    if not evidence or evidence[0][0] is not None:raise ValueError('initial observation missing')
    if next_action not in (0,1):raise ValueError('invalid next action')
    if any(a not in (0,1) for a,o in evidence[1:]):raise ValueError('invalid action')
    for a,ob in evidence:
        if not any(compatible(code,ob) for code in range(4)):
            raise ValueError('impossible observation')
    k=len(evidence)-1
    sink=k+1
    # Current path states are unique, so no observed action conflicts occur.
    transition=[[s,s] for s in range(k+2)]
    for i,(a,o) in enumerate(evidence[1:]):transition[i][a]=i+1
    transition[k][next_action]=sink
    emissions=[next(c for c in range(4) if compatible(c,o)) for a,o in evidence]
    left=WitnessMachine(tuple(tuple(x) for x in transition),tuple(emissions+[0]))
    right=WitnessMachine(tuple(tuple(x) for x in transition),tuple(emissions+[3]))
    return left,right


def replay(machine,evidence,next_action):
    state=machine.start
    assert compatible(machine.emissions[state],evidence[0][1])
    for action,ob in evidence[1:]:
        state=machine.transitions[state][action]
        assert compatible(machine.emissions[state],ob)
    nxt=machine.transitions[state][next_action]
    return machine.emissions[nxt]


def audit_witnesses(seeds=120):
    for seed in range(seeds):
        rng=Random(39101+seed)
        k=rng.randrange(0,20)
        rows=[(None,(rng.choice((None,0,1)),rng.choice((None,0,1))))]
        for _ in range(k):rows.append((rng.randrange(2),(rng.choice((None,0,1)),rng.choice((None,0,1)))))
        act=rng.randrange(2)
        a,b=completion_pair(rows,act)
        assert len(a.emissions)==len(rows)+1
        assert replay(a,rows,act)==0
        assert replay(b,rows,act)==3
    return {'status':'passed','test_cases':seeds,'proof':'two distinct deterministic Moore completions agree with every finite masked observation, but disagree on next full emission','scope':'unbounded hidden-state count; does not contradict certification inside an externally validated finite grammar'}

if __name__=='__main__':
    import json
    print(json.dumps(audit_witnesses(),indent=2))
