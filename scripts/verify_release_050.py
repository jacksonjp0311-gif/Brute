"""Brute v0.5.0 release verification. Raises VerificationError (never assert). New file; verify_release_040 stays frozen.

Release-specific values come from RELEASE.json and the plan/freeze files, not from literals in this verifier, so the
checks are parameterised by version. No study numbers are asserted: derived artifacts are regenerated byte-for-byte and
sealed artifacts are checked against their seals.

Chronology (git ancestry): preregistration < reference < implementation commits < pre-freeze fix commits < source freeze
< scoring scripts < seal commit; the scoring scripts are unchanged after their commit; the ledger has the scoring-script,
run_start and run_end receipts in that order.

  python scripts/verify_release_050.py --fast     # seals, freezes, regenerated gates/paired, ledger, manifest, git order
  python scripts/verify_release_050.py            # also re-runs the second implementation count (long)
"""
from __future__ import annotations
import argparse,json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1];sys.path.insert(0,str(ROOT))
from experiments.brute_common import VerificationError,check,sha,dumps
from experiments.brute_common import load as _load_json


def load(path):
    try:return _load_json(path)
    except (OSError,ValueError) as e:raise VerificationError(f'cannot read {path}: {e}') from None
from scripts.verify_release import _freeze
from scripts.verify_release_020 import ledger_020,_git

PREVIOUS_FREEZES=('experiments/SOURCE_FREEZE.json','experiments/BRUTE_SOURCE_FREEZE_002.json','experiments/BRUTE_RELEASE_FREEZE_010.json',
                  'experiments/BRUTE_SOURCE_FREEZE_003.json','experiments/BRUTE_RELEASE_FREEZE_011.json',
                  'experiments/BRUTE_SOURCE_FREEZE_004.json','experiments/BRUTE_RELEASE_FREEZE_020.json',
                  'experiments/BRUTE_SOURCE_FREEZE_005.json','experiments/BRUTE_RELEASE_FREEZE_030.json',
                  'experiments/BRUTE_SOURCE_FREEZE_006.json','experiments/BRUTE_RELEASE_FREEZE_040.json')
SCORING=('scripts/make_count_007.py','scripts/make_gates_007.py','scripts/make_paired_007.py','scripts/make_reproducibility_007.py')


def _anc(root,a,b):return _git(root,'merge-base','--is-ancestor',a,b).returncode==0


def git_order(root,rel):
    """Process order from ancestry, each step a strict ancestor of the next; plan and scoring scripts unchanged since."""
    check(_git(root,'rev-parse','--git-dir').returncode==0,'not a git checkout')
    fr=load(root/rel['source_freeze'])
    chain=[('preregistration',fr['preregistration_commit']),('reference',fr['reference_commit'])]
    chain+=[(f'implementation_{i}',c) for i,c in enumerate(fr['implementation_commits'])]
    chain+=[(f'pre_freeze_fix_{i}',c) for i,c in enumerate(fr['pre_freeze_fix_commits'])]
    chain+=[('source_freeze',rel['source_freeze_commit']),('scoring_scripts',rel['scoring_scripts_commit']),('seal',rel['seal_commit']),('head','HEAD')]
    for (na,a),(nb,b) in zip(chain,chain[1:]):
        check(_anc(root,a,b),f'{na} {a} is not an ancestor of {nb} {b}')
        if b!='HEAD':check(_git(root,'rev-parse',a).stdout!=_git(root,'rev-parse',b).stdout,f'{na} and {nb} are the same commit')
    plan=_git(root,'show',f"{fr['preregistration_commit']}:{rel['preregistration']}")
    check(plan.returncode==0 and plan.stdout==(root/rel['preregistration']).read_text(),'plan changed after pre-registration')
    sc=rel['scoring_scripts_commit']
    for f in SCORING:
        check(_git(root,'cat-file','-e',f"{rel['source_freeze_commit']}:{f}").returncode!=0,f'{f} existed at the source freeze')
        b=_git(root,'show',f'{sc}:{f}');check(b.returncode==0 and b.stdout==(root/f).read_text(),f'{f} changed after the scoring-script commit')
        check(len(_git(root,'log','--format=%H','--',f).stdout.split())==1,f'{f} has more than one commit')
    t_sc=int(_git(root,'show','-s','--format=%ct',sc).stdout);t_seal=int(_git(root,'show','-s','--format=%ct',rel['seal_commit']).stdout)
    check(t_seal>t_sc,'seal commit not after scoring scripts')
    return {n:c for n,c in chain if c!='HEAD'}


def ledger_order(receipts):
    ev=[r['event'] for r in receipts]
    for e in ('preregistration_007','reference_007','source_freeze_007','scoring_scripts_007','run_start_007','run_end_007'):check(e in ev,'ledger lacks '+e)
    check(ev.index('scoring_scripts_007')<ev.index('run_start_007')<ev.index('run_end_007'),'ledger run chronology')
    return {e:next(r['note'] for r in receipts if r['event']==e)[:160] for e in ('run_start_007','run_end_007')}


def verify(root=ROOT,fast=False,git=True):
    root=Path(root);out={'schema':'brute.verify-release.v5_0'}
    rel=load(root/'RELEASE.json');from brute.release_version_050 import RELEASE_VERSION
    check(rel['version']==RELEASE_VERSION,'RELEASE.json version differs from brute.release_version_050')
    import tomllib;check(tomllib.loads((root/'pyproject.toml').read_text())['project']['version']==RELEASE_VERSION,'pyproject version differs')
    out['locked_files']={f:_freeze(root,f) for f in PREVIOUS_FREEZES+(rel['source_freeze'],rel['release_freeze'])}
    for d in ('results/study-001','results/study-002','results/study-003'):
        seal=load(root/d/'SEAL.json');check(sha(root/d/'SCIENTIFIC.json')==seal['scientific_sha256'],d+' SCIENTIFIC does not match SEAL')
    for d,mod in (('results/study-004','study004_storage'),('results/study-005','study005_storage'),('results/study-006','study006_storage')):
        __import__('scripts.'+mod,fromlist=['ensure_raw']).ensure_raw(root/d);seal=load(root/d/'SEAL.json')
        for n,k in (('RESULTS.json','results_sha256'),('SCIENTIFIC.json','scientific_sha256')):check(sha(root/d/n)==seal[k],f'{d}/{n} does not match SEAL')
    s7=root/rel['results_dir'];from scripts.study007_storage import ensure_raw;ensure_raw(s7);seal=load(s7/'SEAL.json')
    for n,k in (('RESULTS.json','results_sha256'),('SCIENTIFIC.json','scientific_sha256'),('CALIBRATION_007.json','calibration_sha256'),
                ('CALIBRATION_007_TRACES.json','calibration_traces_sha256')):
        check(sha(s7/n)==seal[k],f'study-007 {n} does not match SEAL')
    check(sha(root/rel['preregistration'])==seal['plan_sha256'] and sha(root/rel['source_freeze'])==seal['freeze_sha256'],'study-007 plan/freeze')
    from scripts import make_paired_007,make_gates_007
    for mod,name in ((make_paired_007,'PAIRED_ANALYSIS.json'),(make_gates_007,'GATES.json')):
        check((s7/name).read_bytes()==dumps(mod.build(s7)),f'study-007 {name} does not regenerate byte-for-byte')
    rep=load(s7/'REPRODUCIBILITY.json');check(rep['scientific_sha256']==seal['scientific_sha256'],'reproducibility record is of other results')
    cnt=load(s7/'SECOND_IMPLEMENTATION_COUNT.json');check(cnt['source_results_sha256']==seal['results_sha256'],'second implementation count is of other results')
    check('second implementation by the same author' in cnt['wording'],'second implementation wording')
    if not fast:
        import subprocess,tempfile
        with tempfile.TemporaryDirectory() as tmp:
            r=subprocess.run([sys.executable,'-m','experiments.v050_reference','--results-dir',str(s7),'--workers','6','--mutate','20','--out',tmp+'/c.json'],cwd=root,capture_output=True,text=True)
            check(r.returncode==0 and json.loads(Path(tmp+'/c.json').read_text())==cnt,'second implementation count does not reproduce')
        out['second_implementation']='re-run, identical'
    receipts,sup=ledger_020(root,git);out['ledger_receipts']=len(receipts);out['ledger_superseded']=sup
    out['run_chronology']=ledger_order(receipts)
    sources={r['source'] for r in receipts}
    for need in (rel['preregistration'],rel['source_freeze'],f"{rel['results_dir']}/SEAL.json",f"{rel['results_dir']}/GATES.json"):check(need in sources,'ledger lacks '+need)
    from scripts.make_manifest import build as manifest
    check((root/'MANIFEST.sha256').read_text()==manifest(root),'MANIFEST.sha256 does not match tracked files')
    out['manifest_files']=len((root/'MANIFEST.sha256').read_text().splitlines())
    if git:out['process_order']=git_order(root,rel)
    g=load(s7/'GATES.json');out['gates_passed']=g['passed'];out['gates_failed']=g['failed']
    check(rel['gates_passed']==g['passed'] and rel['gates_failed']==g['failed'],'RELEASE.json gate lists differ from GATES.json')
    for k in ('GM_verdict','GX3_verdict'):
        if k in g:out[k]=g[k];check(rel.get(k)==g[k],f'RELEASE.json {k} differs from GATES.json')
    out['status']='passed'
    out['validity']='bounded deterministic Moore worlds; 2x2 families plus pre-registered breadth families (6 states, 3 sensors, 3 actions); not general intelligence'
    return out


if __name__=='__main__':
    ap=argparse.ArgumentParser();ap.add_argument('--fast',action='store_true');a=ap.parse_args()
    try:print(json.dumps(verify(fast=a.fast),indent=2))
    except VerificationError as e:print('VERIFICATION FAILED:',e);sys.exit(1)
